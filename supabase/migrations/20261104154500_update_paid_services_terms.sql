Version 2.2 — 4 November 2026

1. GENERAL PAYMENT TERMS
1.1. Basic accounts and browsing are free. Paid products and their current prices are shown on the relevant Pricing, posting, or payment page.
1.2. The price shown when you approve the M-Pesa prompt is the price that applies to that purchase. Prices may change for future purchases.
1.3. Payment is collected once, up front, through an M-Pesa STK push to the phone number you enter. We never ask for your M-Pesa PIN.
1.4. A paid product starts only after M-Pesa confirms payment. If payment succeeds but the product is not activated, contact support at itukarua.co.ke/contact with your M-Pesa receipt. We will activate the product or reverse the payment.
1.5. Paid products do not renew automatically. We never charge your number without a new payment request that you approve.

2. JOBSEEKER PREMIUM
2.1. Premium is a 7-day jobseeker subscription priced at KES 100 unless the Pricing page shows a different price at checkout.
2.2. The subscription starts when M-Pesa confirms payment and ends 7 days later, at the same time of day.
2.3. Premium includes unlimited job bids, direct messaging with employers, priority visibility in employer searches, ratings and recommendations, profile analytics, a featured badge, and WhatsApp contact for employers.
2.4. When the 7 days end, the account returns to the Free plan. The profile, bids and messages are kept.
2.5. Paying again before expiry extends the current end date by 7 days rather than replacing it.

3. EMPLOYER ACCESS
3.1. Employer Access is a 7-day subscription. It enables access to jobseeker profiles and contact details in the employer's category, direct messaging, bid management, hiring tools, and unlimited job posting during the active period.
3.2. Single Job Access is a one-day product for one job. It unlocks the contacts and bids associated with that job for 24 hours, unless the payment page shows a different access window.
3.3. Employer Access and Single Job Access end automatically at the displayed expiry time and do not renew automatically.

4. CONTACT AND TOP-RATED ACCESS
4.1. Contact Access is a one-day purchase that unlocks one eligible worker contact for the displayed access window, normally 24 hours.
4.2. Top Rated Day Pass is a one-day purchase that provides contact access to the eligible Top Rated worker snapshot shown when the pass is purchased, normally for 24 hours.
4.3. These access products do not guarantee that a worker will respond, accept work, remain available, or provide accurate information.

5. ADVERTS AND JOB LISTINGS
5.1. A 10-Day, 20-Day, or 30-Day advert or job listing keeps the submitted listing live for the duration and price displayed at checkout, subject to moderation and the Platform Terms.
5.2. The listing duration starts when payment is confirmed and the listing is activated. Expiry does not renew automatically.
5.3. Listing fees cover publication and the stated listing features. They do not guarantee views, leads, bids, employment, sales, or completed work.

6. FEATURED BOOST
6.1. Featured Boost is a separate paid placement product that promotes an eligible advert in featured positions for the duration shown at checkout, normally 7 days.
6.2. A Featured Boost does not guarantee a particular ranking, number of views, enquiries, or conversion. It ends automatically and does not renew automatically.

7. OTHER PAID BUSINESS PLACEMENTS
7.1. Corporate and other negotiated placements are charged according to the written quote or invoice accepted by the customer. The quote states the placement, duration, amount, and payment terms.
7.2. A negotiated placement starts after payment or the agreed invoice commencement condition is met and ends at the stated expiry date. It does not renew unless the written agreement says so.

8. REFUNDS AND RESPONSIBILITIES
8.1. Once a paid product is active, its payment is non-refundable because access or publication is granted immediately, except where the law requires otherwise.
8.2. If M-Pesa charges you but the paid product is not delivered, contact support with your receipt. We do not keep money for a service that was not delivered.
8.3. Nothing here removes rights you have under the Consumer Protection Act, 2012.
8.4. Paid products do not guarantee employment, interviews, responses, sales, views, or successful transactions.
8.5. An account or listing suspended for breaching the Terms is not refunded for the remaining period where the breach caused the suspension.

